    private final OrderService orders = new OrderService();

    private Window owner;
    private User actor;
    private Runnable onSaved;

    public NewOrderDialog(Window owner, User actor, Runnable onSaved) {
        super(owner, "New Walk-in Order", ModalityType.APPLICATION_MODAL);
        this.owner = owner;
        this.actor = actor;
        this.onSaved = onSaved;
        initComponents();
        for (User u : new UserDAO().search(null, Role.CUSTOMER)) if (u.isActive()) customer.addItem(u);
        for (LaundryService s : new CatalogService().list(true)) service.addItem(s);
        method.setSelectedItem(PaymentMethod.CASH);
        Runnable recalc = () -> {
            LaundryService s = (LaundryService) service.getSelectedItem();
            if (s == null) return;
            BigDecimal q = BigDecimal.valueOf((Double) qty.getValue());
            total.setText(Formats.peso(orders.computeTotal(s, q)) + "  (" + Formats.peso(s.getPrice()) + " / " + s.unitLabel() + ")");
            boolean on = payNow.isSelected();
            method.setEnabled(on);
            ref.setEnabled(on && method.getSelectedItem() == PaymentMethod.GCASH);
        };
        service.addActionListener(e -> recalc.run());
        qty.addChangeListener(e -> recalc.run());
        payNow.addActionListener(e -> recalc.run());
        method.addActionListener(e -> recalc.run());
        recalc.run();
        addCustomer.addActionListener(e -> {
            UserFormDialog d = new UserFormDialog(this, null, Role.CUSTOMER, false);
            d.setVisible(true);
            if (d.saved() != null) { customer.addItem(d.saved()); customer.setSelectedItem(d.saved()); }
        });
        save.addActionListener(e -> {
            User cu = (User) customer.getSelectedItem();
            LaundryService s = (LaundryService) service.getSelectedItem();
            if (cu == null || s == null) { Dialogs.info(this, "Please select a customer and a service."); return; }
            final Order[] created = new Order[1];
            boolean ok = Dialogs.run(this, () -> {
                created[0] = orders.placeOrder(cu.getId(), s.getId(), BigDecimal.valueOf((Double) qty.getValue()),
                        notes.getText(), actor);
                if (payNow.isSelected())
                    new PaymentService().submit(created[0].getId(), (PaymentMethod) method.getSelectedItem(), ref.getText(), actor);
            });
            if (ok) {
                Dialogs.info(this, "Order " + created[0].getOrderNo() + " created for " + cu.getFullName() + ".");
                onSaved.run();
                dispose();
            } else if (created[0] != null) {
                onSaved.run();       
                dispose();
            }
        });
        pack();
        setLocationRelativeTo(owner);
    }

    private int row(JPanel p, GridBagConstraints c, int y, String label, JComponent field) {
        c.gridx = 0; c.gridy = y; c.weightx = 0;
        p.add(Theme.label(label, Font.PLAIN, 13, Theme.MUTED), c);
        c.gridx = 1; c.weightx = 1;
        field.setPreferredSize(new Dimension(300, 34));
        p.add(field, c);
        return y + 1;
    }

