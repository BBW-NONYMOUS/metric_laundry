    public UserFormDialog(Window owner, User existing, Role defaultRole, boolean canChooseRole) {
        super(owner, existing == null ? "Add " + defaultRole.label() : "Edit " + existing.getFullName(),
                ModalityType.APPLICATION_MODAL);
        this.owner = owner;
        this.existing = existing;
        this.defaultRole = defaultRole;
        this.canChooseRole = canChooseRole;
        this.isNew = existing == null;
        initComponents();
        role.setSelectedItem(isNew ? defaultRole : existing.getRole());
        save.addActionListener(e -> {
            User u = isNew ? new User() : existing;
            u.setFullName(name.getText().trim());
            u.setUsername(username.getText().trim());
            u.setPhone(phone.getText().trim());
            u.setEmail(email.getText().trim());
            u.setAddress(address.getText().trim());
            u.setRole((Role) role.getSelectedItem());
            u.setActive(active.isSelected());
            AuthService auth = new AuthService();
            if (Dialogs.run(this, () -> {
                if (isNew) auth.createUser(u, new String(pw.getPassword()), new String(pw2.getPassword()));
                else auth.updateUser(u);
            })) {
                saved = u;
                dispose();
            }
        });
        pack();
        setLocationRelativeTo(owner);
    }

    public User saved() { return saved; }

