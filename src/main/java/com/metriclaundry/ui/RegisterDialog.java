    public RegisterDialog(Frame owner) {
        super(owner, "Create Customer Account", true);
        this.owner = owner;
        initComponents();
        create.addActionListener(e -> {
            User u = new User();
            u.setFullName(name.getText().trim());
            u.setUsername(user.getText().trim());
            u.setPhone(phone.getText().trim());
            u.setEmail(email.getText().trim());
            u.setAddress(address.getText().trim());
            if (Dialogs.run(this, () -> new AuthService().registerCustomer(u,
                    new String(pw.getPassword()), new String(pw2.getPassword())))) {
                Dialogs.info(this, "Account created! You can now log in as \"" + u.getUsername() + "\".");
                dispose();
            }
        });
        pack();
        setLocationRelativeTo(owner);
    }

